import { JSDOM, VirtualConsole } from 'jsdom';

const base=process.argv[2];
const errors=[];
const virtualConsole=new VirtualConsole();
virtualConsole.on('error',message=>errors.push(String(message)));
const dom=await JSDOM.fromURL(base,{resources:'usable',runScripts:'dangerously',pretendToBeVisual:true,virtualConsole,beforeParse(window){window.fetch=(input,init)=>fetch(new URL(typeof input==='string'?input:input.url,base),init);window.scrollTo=()=>{};window.HTMLElement.prototype.scrollIntoView=()=>{};window.navigator.clipboard={writeText:async text=>{window.__copied=text;}};window.open=url=>{window.__opened=String(url);return null;};}});
const {document}=dom.window;
await waitFor(()=>document.querySelectorAll('.product-card').length===24);
const multi=[...document.querySelectorAll('.product-card')].find(card=>card.querySelectorAll('.axis-swatch,.variant-pill').length>1);
if(!multi)throw new Error('multi-variant card missing');
multi.querySelector('.card-open').click();
const before=document.querySelector('.add-cart').dataset.cartId;
const selector=[...document.querySelectorAll('.dialog-axis-selectors button')].find(button=>!button.classList.contains('active')&&!button.disabled);
if(!selector)throw new Error('non-default selector missing');
selector.click();
const selected=document.querySelector('.add-cart').dataset.cartId;
if(selected===before)throw new Error('variant sourceId did not change');
document.querySelector('.dialog-favorite').click();
if(!JSON.parse(dom.window.localStorage.getItem('forma-next-favorites')).includes(selected))throw new Error('favorite lost selected sourceId');
document.querySelector('.add-cart').click();
document.querySelector('#dialog-close').click();
document.querySelector('[data-action="cart"]').click();
if(document.querySelector('#order-title')?.textContent!=='Ваш заказ')throw new Error('order screen missing');
const unit=Number(document.querySelector('.order-item strong').textContent.replace(/\D/g,''));
document.querySelector('[data-qty="1"]').click();
const stored=JSON.parse(dom.window.localStorage.getItem('forma-next-cart'));
if(stored[selected]!==2)throw new Error('quantity was not persisted');
if(Number(document.querySelector('.order-item strong').textContent.replace(/\D/g,''))!==unit*2)throw new Error('line total is incorrect');
if(!document.querySelector('.checkout-order')||document.querySelector('.checkout-order').textContent!=='Оформить заказ')throw new Error('checkout action missing');
document.querySelector('.checkout-order').click();
document.querySelector('[data-checkout="whatsapp"]').click();
if(!document.querySelector('#checkout-error').textContent.includes('Укажите имя'))throw new Error('checkout validation missing');
document.querySelector('#checkout-name').value='Тест';document.querySelector('#checkout-phone').value='+7 999 123-45-67';document.querySelector('#checkout-city').value='Москва';
document.querySelector('[data-checkout="whatsapp"]').click();
if(!dom.window.__opened?.startsWith('https://wa.me/79057267946?text=')||!decodeURIComponent(dom.window.__opened).includes('2 шт.'))throw new Error('checkout destination or text invalid');
document.querySelector('#checkout-close').click();
await document.querySelector('.share-order').click();
if(!dom.window.__copied?.includes(`order=${selected}.2`))throw new Error('share URL missing sourceId and quantity');
if(errors.length)throw new Error(errors.join('; '));
if(document.querySelector('.announcement'))throw new Error('announcement present');
if(!document.querySelector('.site-footer'))throw new Error('footer missing');
console.log(`state: PASS (variant ${selected}, quantity 2, totals, checkout, share)`);
dom.window.close();
async function waitFor(predicate){const start=Date.now();while(!predicate()){if(Date.now()-start>20000)throw new Error('timeout');await new Promise(resolve=>setTimeout(resolve,50));}}
